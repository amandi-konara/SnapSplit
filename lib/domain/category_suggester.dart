  /// Returns a category id, or [Category.otherId] when nothing matches.
  static String suggest(String itemName) {
    final name = ' ${_normalise(itemName)} ';
    if (name.trim().isEmpty) return Category.otherId;
    for (final entry in keywords.entries) {
      for (final keyword in entry.value) {
        if (name.contains(' $keyword')) return entry.key;
      }
    }
    return Category.otherId;
  }

  /// Lower case, letters/digits/&/- only, single spaces.
  static String _normalise(String text) => text
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9&\- ]'), ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
}
